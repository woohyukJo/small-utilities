// The mobile observer uses the same tested detector as the desktop app.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
function moduleExpression(file) {
  const compiled = path.join(root, 'dist', file.replace(/\.ts$/, '.js'));
  if (!fs.existsSync(compiled) || fs.statSync(compiled).mtimeMs < fs.statSync(path.join(root, 'src', file)).mtimeMs)
    throw new Error('Run npm run build before generating the mobile observer.');
  const javascript = fs.readFileSync(compiled, 'utf8');
  if (/\brequire\s*\(/.test(javascript)) throw new Error('Mobile observer must remain self-contained');
  return `(() => { const exports = {}; ${javascript}\n return exports; })()`;
}
const output = `// Generated by scripts/build-mobile-probe.cjs; edit src/page-probe.ts and src/turn-tracker.ts instead.
(() => {
  const config = /*BREAKDOWN_CONTEXT*/;
  const { readChatPage } = ${moduleExpression('page-probe.ts')};
  const { TurnTracker } = ${moduleExpression('turn-tracker.ts')};
  const snapshot = readChatPage();
  let events = [];
  if (config.conversationId && snapshot.conversationId === config.conversationId) {
    let observer = globalThis.__breakdownMobileObserver;
    if (!observer || observer.scope !== config.scope) {
      observer = { scope: config.scope, tracker: new TurnTracker(config.pendingUserIds, config.abortedUserIds) };
      globalThis.__breakdownMobileObserver = observer;
    }
    events = observer.tracker.accept(snapshot);
  }
  return JSON.stringify({ scope: config.scope, snapshot, events });
})()
`;
const asset = path.join(root, 'android', 'app', 'src', 'main', 'assets', 'chat-probe.js');
fs.mkdirSync(path.dirname(asset), { recursive: true });
fs.writeFileSync(asset, output);
console.log('Generated Android ChatGPT observer from desktop sources.');
